/**
 * 组装用户消息。
 *
 * @param {object} p
 * @param {string} [p.rawText]   用户粘贴/转发的文本
 * @param {boolean} [p.hasImage] 是否附带图片
 * @returns {string}
 */
function buildUserPrompt(p = {}) {
  const hasImage = !!p.hasImage;
  const text = typeof p.rawText === 'string' ? p.rawText.trim() : '';

  if (hasImage && text) {
    return `下面是一条群通知，包含图片和文字两部分，请一起理解。\n\n【文字部分】\n${text}\n\n【图片部分】\n见随附图片。请先读取图片里的文字，再和上面的文字合并理解。`;
  }
  if (hasImage) {
    return '下面是一条群通知的图片，请先读取图片里的全部文字，然后解构它。';
  }
  if (text) {
    return `下面是一条群通知，请解构它。\n\n${text}`;
  }
  return '（没有收到任何内容）';
}

