'use strict';

/**
 * 时间解析器 · 真实语料回归测试
 *
 * 运行方式（不需要微信环境、不需要云开发）：
 *   node apps/mingbaika/cloudfunctions/parseNotice/tests/time-parser-corpus.test.js
 *
 * 为什么单独有这份测试：
 *   core.test.js 里的时间用例是"围绕实现写的"，覆盖的是我想到的写法。
 *   这份测试反过来——**先从真实家长群通知里收集表述，再对照期望值**，
 *   所以它能发现"实现没想到要支持"的缺口。
 *
 *   初版语料一跑就暴露 6 处 bug，其中两处危害最大：
 *     · 「请于15号前交回执」——中文通知最高频的写法，完全没覆盖
 *     · 「本周末前」——算出的是**上一周**的周日，即一个已经过去的日期
 *   这类"答案错但不报错"最危险，因此这些用例必须长期钉在这里。
 *
 * 固定参考日：2026-10-08（周四）
 *   周一 10-05 / 周二 10-06 / 周三 10-07 / 周四 10-08（今天）
 *   周五 10-09 / 周六 10-10 / 周日 10-11
 */

const path = require('path');
const { parseDeadline, makeRef, DEADLINE_CUES } = require(
  path.join(__dirname, '..', 'core', 'time-parser.js')
);

const REF = makeRef(2026, 10, 8);

// ---------------------------------------------------------------------------
// 迷你断言器（与 core.test.js 保持一致的风格）
// ---------------------------------------------------------------------------
let pass = 0, fail = 0;
const failures = [];

function t(name, fn) {
  try {
    fn();
    pass++;
  } catch (e) {
    fail++;
    failures.push({ name, msg: e.message });
  }
}
function ok(v, msg) { if (!v) throw new Error(msg || '断言失败'); }
function eq(a, b, msg) {
  const x = JSON.stringify(a), y = JSON.stringify(b);
  if (x !== y) throw new Error(`${msg || '值不相等'}\n      期望: ${y}\n      实际: ${x}`);
}

// ---------------------------------------------------------------------------
// 语料
// ---------------------------------------------------------------------------
const CASES = [];
function sec(title) { CASES.push({ section: title }); }
function c(text, ref, expect, note) { CASES.push({ text, ref, expect, note }); }

sec('A. 完整绝对日期');
c('2026-10-10 前交回执', REF, '2026-10-10');
c('定于2026年10月10日秋游', REF, '2026-10-10');
c('2026/10/10 截止报名', REF, '2026-10-10');
c('请于 2026.10.10 前提交', REF, '2026-10-10');
c('预计2027年3月1日开学', REF, '2027-03-01');

sec('B. 月日（含各种分隔符与中文数字）');
c('9月30日前交费', REF, '2026-09-30');
c('10月10日前交秋游费', REF, '2026-10-10');
c('10月10号前', REF, '2026-10-10');
c('10.10前提交', REF, '2026-10-10');
c('10/10 截止', REF, '2026-10-10');
c('10-10 前', REF, '2026-10-10');
c('十月十日交秋游费', REF, '2026-10-10');
c('十二月三十一日前完成', REF, '2026-12-31');
c('1月5日前', REF, '2027-01-05', '已过去超 30 天 → 按明年');

sec('C. 相对日');
c('明天带来', REF, '2026-10-09');
c('后天家长会', REF, '2026-10-10');
c('大后天体检', REF, '2026-10-11');
c('今天下午接孩子', REF, '2026-10-08');

sec('D. 周表述（★ 含周末，此前「本周末」会算出已过去的日期）');
c('本周五前交秋游费', REF, '2026-10-09');
c('这周三', REF, '2026-10-07');
c('下周一交表', REF, '2026-10-12');
c('下周三下午5点前', REF, '2026-10-14');
c('周五前交', REF, '2026-10-09');
c('周六前把作业交了', REF, '2026-10-10');
c('周日休息', REF, '2026-10-11');
c('星期天返校', REF, '2026-10-11');
c('礼拜五交', REF, '2026-10-09');
c('本周末前', REF, '2026-10-11', '★ 曾经错到 10-04（上一周周日）');
c('下周末前', REF, '2026-10-18', '★ 曾经错到 10-11');
c('周末前把回执交了', REF, '2026-10-11');

sec('E. 月首末（★ 含中文月份，此前「十月底」会被当成"本月月底"）');
c('月底前交', REF, '2026-10-31');
c('本月底前', REF, '2026-10-31');
c('月末完成', REF, '2026-10-31');
c('下月初报名', REF, '2026-11-01');
c('11月中旬', REF, '2026-11-15');
c('十月底前交表格', makeRef(2026, 9, 15), '2026-10-31', '★ 非 10 月时曾经错到 9-30');
c('十一月底前完成填报', REF, '2026-11-30', '★ 曾经错到 10-31');
c('十二月底前', REF, '2026-12-31');
c('1月底前', REF, '2027-01-31', '已过去超 30 天 → 按明年');
c('二月底前', makeRef(2026, 1, 15), '2026-02-28', '按该月实际天数');

sec('F. 裸日号（★ 中文通知最高频的期限写法，此前完全没覆盖）');
c('请于15号前交回执', REF, '2026-10-15', '★ 最典型的漏解析');
c('20日前完成填报', REF, '2026-10-20');
c('请于 25 号前交费', REF, '2026-10-25');
c('十号前', REF, '2026-10-10');
c('二十五日前', REF, '2026-10-25');
c('5号前', REF, '2026-11-05', '日号 < 今天 → 推断为下月');
c('8号前', REF, '2026-10-08', '日号 == 今天 → 本月（当天截止）');
c('31号前', REF, '2026-10-31');
c('本月15号前', REF, '2026-10-15');
c('这月20日前', REF, '2026-10-20');
c('下月5号前报名', REF, '2026-11-05');
c('2月29号前', makeRef(2026, 2, 10), null, '2026 非闰年，该月没有 29 号 → 不硬编');
c('29号前', makeRef(2028, 2, 10), '2028-02-29', '2028 是闰年');

sec('G. 相对天数');
c('3日内回复', REF, '2026-10-11');
c('七日内完成', REF, '2026-10-15');

sec('H. 时间点（与日期分离）');
c('本周五下午3点前', REF, '2026-10-09');
c('10月10日 17:30 截止', REF, '2026-10-10');
c('下周三早上7点半集合', REF, '2026-10-14');

sec('I. 误报防护（这些都不该解析出日期）');
c('通知内容如下：请交秋游费', REF, null, '「内容」的「内」不是期限信号');
c('请在教室里等候', REF, null);
c('目前暂无安排', REF, null, '「目前」不是期限信号');
c('从1号楼接孩子', REF, null, '「1号楼」是设施名');
c('请到2号门接孩子', REF, null, '「2号门」是设施名');
c('坐3号线到校', REF, null, '「3号线」是线路名');
c('第2号文件已下发', REF, null, '编号，不是日期');
c('国庆后另行通知', REF, null);
c('每天早上7点集合', REF, null, '只有时间点，没有日期');
c('请自带水杯和雨衣', REF, null);
c('当日凭票入场', REF, null, '「当天/当日」指前面提到的那一天，不是今天，不能当成今天');
c('2月29日前', makeRef(2026, 2, 10), null, '★ 曾因 Date.UTC 静默溢出被算成 3-01');

// ---------------------------------------------------------------------------
// 逐条执行
// ---------------------------------------------------------------------------
console.log('\n时间解析器 · 真实语料回归\n');
console.log('参考日 ' + REF.toISOString().slice(0, 10) + '（周四）\n');

let curSection = '';
let secTotal = 0, secBad = 0;
const badRows = [];

function flushSection() {
  if (curSection && secBad) {
    console.log(`  ${secBad}/${secTotal} 条未通过`);
  }
  secTotal = 0; secBad = 0;
}

for (const row of CASES) {
  if (row.section) {
    flushSection();
    console.log(row.section);
    curSection = row.section;
    continue;
  }
  const out = parseDeadline(row.text, row.ref);
  const got = out.date;
  const okCase = row.expect === null ? got === null : got === row.expect;
  secTotal++;
  if (!okCase) {
    secBad++;
    badRows.push({ ...row, got });
    console.log(`    \u2717 ${row.text}  → ${got || '(无)'}  期望 ${row.expect || '(无)'}${row.note ? '   [' + row.note + ']' : ''}`);
  }
}
flushSection();

// ---------------------------------------------------------------------------
// 逐个断言（让失败明细进入统一汇总，退出码也由这里决定）
// ---------------------------------------------------------------------------
t('语料全量断言', () => {
  if (badRows.length) {
    throw new Error(
      `${badRows.length} 条不符：\n      ` +
      badRows.map((r) => `${r.text} → ${r.got || '(无)'}，期望 ${r.expect || '(无)'}`).join('\n      ')
    );
  }
});

// ---------------------------------------------------------------------------
// 置信度契约：低置信的推断必须落在阈值以下，前端才会并列展示原文
// ---------------------------------------------------------------------------
console.log('\n置信度契约（阈值 0.7：低于此值前端并列展示原文供老人核对）');

t('裸日号是推断，置信度必须 < 0.7 以触发原文核对', () => {
  const o = parseDeadline('请于15号前交回执', REF);
  ok(o.date === '2026-10-15', '日期应为 2026-10-15');
  ok(o.confidence < 0.7, `置信度应 < 0.7，实际 ${o.confidence}`);
});

t('明确写法（带月份/周）置信度应 >= 0.7，不必打扰用户', () => {
  const samples = ['10月10日前交费', '本周五前交秋游费', '本月15号前'];
  samples.forEach((s) => {
    const o = parseDeadline(s, REF);
    ok(o.confidence >= 0.7, `${s} 置信度应 >= 0.7，实际 ${o.confidence}`);
  });
});

t('「本周末前」这类明确表述不必触发原文核对', () => {
  const o = parseDeadline('本周末前', REF);
  ok(o.date === '2026-10-11', '日期应为 2026-10-11');
  ok(o.confidence >= 0.7, `置信度应 >= 0.7，实际 ${o.confidence}`);
});

t('带备注的未来月份不受"下月"影响', () => {
  const o = parseDeadline('下月5号前报名', REF);
  eq(o.date, '2026-11-05');
});

// ---------------------------------------------------------------------------
// 期限信号词：收窄后不能再被「内容」「目前」这类词误触发
// ---------------------------------------------------------------------------
console.log('\n期限信号词（收窄后）');

t('「内容」「室内」「目前」不应被判为期限信号', () => {
  ['通知内容如下', '请在室内等候', '目前暂无安排'].forEach((s) => {
    ok(!DEADLINE_CUES.test(s), `「${s}」不应触发期限信号`);
  });
});

t('真正的期限表述应被判为期限信号', () => {
  ['15号前交', '3日内回复', '截止日期', '截至本周五'].forEach((s) => {
    ok(DEADLINE_CUES.test(s), `「${s}」应触发期限信号`);
  });
});

t('误报防护：没有期限的通知不应产生"有期限但没读懂"的假信号', () => {
  const o = parseDeadline('通知内容如下：请交秋游费', REF);
  eq(o.date, null, '不应解析出日期');
  eq(o.cue, false, '不应被判为含期限信号');
});

// ---------------------------------------------------------------------------
console.log('\n' + '-'.repeat(56));
console.log(`通过 ${pass} 项，失败 ${fail} 项`);
if (fail) {
  console.log('\n失败明细：');
  failures.forEach((f) => console.log('  - ' + f.name + '\n      ' + f.msg));
  process.exit(1);
} else {
  console.log('全部通过 ✅');
}
